// Generates src/api/schema.d.ts from the backend's /v3/api-docs (npm run gen:api).
import { writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';

const url = process.argv[2] ?? 'http://localhost:8080/v3/api-docs';
const doc = await (await fetch(url)).json();

// Fields with a default are request-side optional, not "always present".
const ast = await openapiTS(doc, { defaultNonNullable: false });
writeFileSync(
  'src/api/schema.d.ts',
  `/** GENERATED by \`npm run gen:api\` from ${url} — do not edit. */\n\n${astToString(ast)}`,
);
console.log(`src/api/schema.d.ts generated from ${url}`);
